"""Northbridge Industries is a fictional company.

History is generated by the same statement engine as the forecast, with the
drivers below, so the statements tie. It is not a filing. Segment figures are
an allocation of consolidated results. Peer multiples are assumed, not
independently modeled companies.
"""

from __future__ import annotations

from valuation.case import (
    Assumptions,
    Case,
    LboAssumptions,
    Peer,
    Segment,
    Statements,
)
from valuation.statements import (
    DAYS,
    CorporatePolicy,
    OperatingDrivers,
    Stocks,
    project,
)

# Steady-state margins. Segment margins are set so they exceed this by the
# corporate drag: 0.50*0.22 + 0.30*0.40 + 0.20*0.20 - 0.03 = 0.24.
GROSS_MARGIN = 0.40
OPEX_PCT = 0.16
DSO = 50.0
DIO = 55.0
DPO = 40.0


def _opening() -> tuple[int, Stocks]:
    # Notional 2020 activity, used only to size opening working capital.
    revenue = 450.0
    cogs = revenue * (1.0 - GROSS_MARGIN)
    cash = 140.0
    ar = revenue * DSO / DAYS
    inventory = cogs * DIO / DAYS
    ppe = 420.0
    ap = cogs * DPO / DAYS
    debt = 200.0
    equity = cash + ar + inventory + ppe - ap - debt
    return 2020, Stocks(
        cash=cash,
        ar=ar,
        inventory=inventory,
        ppe=ppe,
        other_assets=0.0,
        ap=ap,
        debt=debt,
        other_liabilities=0.0,
        equity=equity,
    )


def _history() -> Statements:
    opening_year, opening = _opening()
    revenues = {2021: 500.0, 2022: 560.0, 2023: 625.0, 2024: 690.0, 2025: 760.0}
    years = []
    for year, revenue in revenues.items():
        years.append(
            (
                OperatingDrivers(
                    year=year,
                    revenue=revenue,
                    gross_margin=GROSS_MARGIN,
                    opex_pct_sales=OPEX_PCT,
                    da_pct_begin_ppe=0.08,
                    capex_pct_sales=0.06,
                    tax_rate=0.25,
                    dso=DSO,
                    dio=DIO,
                    dpo=DPO,
                ),
                CorporatePolicy(
                    interest_rate=0.06,
                    dividend_payout=0.20,
                    minimum_cash=40.0,
                    debt_paydown=12.0,
                ),
            )
        )
    return project(opening_year, opening, years, interest="beginning").statements


